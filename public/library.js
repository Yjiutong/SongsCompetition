for (const group of SONG_LIBRARY_GROUPS) {
  for (const name of Object.keys(SONG_LIBRARY[group])) {
    SONG_LIBRARY_SONGS[name] = SONG_LIBRARY[group][name];
    SONG_LIBRARY_GROUP_OF[name] = group;
  }
}

// 平铺索引：[{ group, name, title }]，便于搜索与统计
const SONG_LIBRARY_FLAT = [];
for (const group of SONG_LIBRARY_GROUPS) {
  for (const name of Object.keys(SONG_LIBRARY[group])) {
    for (const title of SONG_LIBRARY[group][name]) {
      SONG_LIBRARY_FLAT.push({ group, name, title });
    }
  }
}
